function applyLang(lang) {
  document.documentElement.setAttribute('lang', lang);
  var dict = I18N[lang] || I18N.es;
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    var key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });
  var esBtn = document.getElementById('langEs'), enBtn = document.getElementById('langEn');
  if (esBtn) esBtn.classList.toggle('active', lang === 'es');
  if (enBtn) enBtn.classList.toggle('active', lang === 'en');
  if (typeof window.playHeroTyping === 'function') window.playHeroTyping();
}

window.setLang = function (lang) {
  applyLang(lang);
  try { localStorage.setItem('quantiq_lang', lang); } catch (e) {}
};

(function () {
  var saved = 'es';
  try { saved = localStorage.getItem('quantiq_lang') || 'es'; } catch (e) {}
  if (saved !== 'es') applyLang(saved);
})();

(function () {
  var reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  /* ── Hero headline typing effect (re-playable on language switch) ── */
  var heroTypeTimer = null, heroTypeCursorTimeout = null;
  function playHeroTyping() {
    var typeEl = document.getElementById('heroEmType');
    if (!typeEl) return;
    if (heroTypeTimer) { clearInterval(heroTypeTimer); heroTypeTimer = null; }
    if (heroTypeCursorTimeout) { clearTimeout(heroTypeCursorTimeout); heroTypeCursorTimeout = null; }
    var existingCursor = typeEl.querySelector('.type-cursor');
    if (existingCursor) existingCursor.remove();
    var fullText = typeEl.textContent;
    if (reduced) { typeEl.textContent = fullText; return; }
    typeEl.textContent = '';
    var cursor = document.createElement('span');
    cursor.className = 'type-cursor';
    typeEl.appendChild(cursor);
    var i = 0;
    heroTypeTimer = setInterval(function () {
      if (i < fullText.length) {
        cursor.insertAdjacentText('beforebegin', fullText.charAt(i));
        i++;
      } else {
        clearInterval(heroTypeTimer);
        heroTypeTimer = null;
        heroTypeCursorTimeout = setTimeout(function () {
          if (cursor.parentNode) cursor.parentNode.removeChild(cursor);
        }, 900);
      }
    }, 55);
  }
  window.playHeroTyping = playHeroTyping;
  if (document.getElementById('heroEmType')) { setTimeout(playHeroTyping, 450); }

  /* ── Scroll reveal ── */
  var revealEls = document.querySelectorAll('.reveal');
  if ('IntersectionObserver' in window && !reduced) {
    var io = new IntersectionObserver(function (entries) {
      entries.forEach(function (e) {
        if (e.isIntersecting) { e.target.classList.add('on'); io.unobserve(e.target); }
      });
    }, { threshold: 0.15 });
    revealEls.forEach(function (el) { io.observe(el); });
  } else {
    revealEls.forEach(function (el) { el.classList.add('on'); });
  }

  /* ── Count-up stats ── */
  var counters = document.querySelectorAll('.count');
  function animate(el) {
    var target = parseInt(el.dataset.target, 10);
    if (reduced) { el.textContent = target; return; }
    var start = null, dur = 1400;
    function frame(t) {
      if (!start) start = t;
      var k = Math.min((t - start) / dur, 1);
      k = 1 - Math.pow(1 - k, 3);
      el.textContent = Math.round(target * k);
      if (k < 1) requestAnimationFrame(frame);
    }
    requestAnimationFrame(frame);
  }
  if ('IntersectionObserver' in window) {
    var io2 = new IntersectionObserver(function (entries) {
      entries.forEach(function (e) {
        if (e.isIntersecting) { animate(e.target); io2.unobserve(e.target); }
      });
    }, { threshold: 0.6 });
    counters.forEach(function (el) { io2.observe(el); });
  } else {
    counters.forEach(function (el) { el.textContent = el.dataset.target; });
  }

  /* ── Chat loop ── */
  var msgs = Array.prototype.slice.call(document.querySelectorAll('#chatBody .msg'));
  var typing = document.getElementById('typing');
  if (reduced) {
    msgs.forEach(function (m) { m.classList.add('show'); });
  } else {
    var i = 0;
    function next() {
      if (i >= msgs.length) {
        setTimeout(function () {
          msgs.forEach(function (m) { m.classList.remove('show'); });
          i = 0;
          setTimeout(next, 900);
        }, 5200);
        return;
      }
      var m = msgs[i];
      var isAgent = m.classList.contains('out');
      if (isAgent) {
        typing.classList.add('show');
        setTimeout(function () {
          typing.classList.remove('show');
          m.classList.add('show');
          i++;
          setTimeout(next, 1400);
        }, 1100);
      } else {
        m.classList.add('show');
        i++;
        setTimeout(next, 1400);
      }
    }
    setTimeout(next, 800);
  }
})();